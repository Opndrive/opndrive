/**
 * The S3-compatible providers we support, and everything the app knows about
 * each one.
 *
 * This is the single source of truth. The routes under /connect/[provider], the
 * metadata on those pages, the sitemap entries, the picker cards and the setup
 * guide all read from here, so adding a provider is one edit rather than five.
 *
 * A word on why these pages are allowed to exist at all. Google penalises
 * "scaled content abuse": many pages identical but for one swapped variable.
 * These pages are defensible only because each provider genuinely differs -
 * different endpoint shape, different regions, different CORS steps, different
 * permission names. Keep it that way. A provider added here with copied copy
 * and an empty setup section is a doorway page, and those are penalised site
 * wide rather than page by page.
 */

export interface RegionOption {
  value: string;
  label: string;
}

export interface S3Provider {
  /** URL segment. Written the way people search, not the way we store it. */
  slug: string;
  /** Key into the CORS policies in config/cors.ts. */
  id: string;
  name: string;
  /** One line on the picker card. */
  tagline: string;
  /**
   * Endpoint template. `{{region}}` is the only placeholder substituted.
   * A template carrying any other one cannot be derived from what we ask
   * the user for, so it must be supplied by hand - see
   * `requiresCustomEndpoint`, which R2 sets for exactly that reason.
   */
  endpoint: string;
  defaultRegion: string;
  regions: RegionOption[];
  /** True when the endpoint cannot be derived and the user must supply it. */
  requiresCustomEndpoint: boolean;
  /**
   * What to show in an empty endpoint field, for a provider whose endpoint
   * cannot be derived from anything we ask for.
   *
   * `endpoint` is a template and was being used for this directly, so R2
   * offered the user a literal `{{accountId}}` - our own templating syntax,
   * presented as the thing to type, on a page we are trying to rank. Where
   * the region is the only variable, `resolveEndpoint` fills it in and the
   * hint under the field carries the real URL, so only R2 needs one of these.
   */
  endpointPlaceholder?: string;
  seo: {
    title: string;
    description: string;
    h1: string;
    /** Opening paragraph. Provider-specific, never generated by templating. */
    intro: string;
  };
  setup: {
    corsInstructions: string;
    permissions: string[];
    docsUrl: string;
    docsLabel: string;
    /** Anything about this provider that trips people up. */
    gotcha?: string;
    /**
     * Failures particular to this provider, shown after the ones every
     * provider shares in the "If it fails" section. Each must be something
     * the provider documents or the app's own code shows, never a guess.
     */
    troubleshooting?: string[];
  };
}

